// Genera supabase/catalogo.sql a partir de lessons/curso.json y de cada lección:
// las filas de portuguese_units y portuguese_lessons que necesitan las claves foráneas
// del progreso. Solo inserta o actualiza (on conflict): nunca borra nada, así que
// volver a ejecutarlo no toca el progreso de nadie.
//
//   npm run catalogo-sql   → escribe supabase/catalogo.sql (luego se ejecuta en el SQL Editor)

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { revisarCurso, revisarLeccion } from '../js/lessons.js';

const raiz = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const leer = async archivo => JSON.parse((await readFile(path.join(raiz, archivo), 'utf8')).replace(/^\uFEFF/, ''));
const texto = v => `'${String(v).replace(/'/g, "''")}'`;

const { unidades, fatal } = revisarCurso(await leer('lessons/curso.json'));
if (fatal) {
  console.error('lessons/curso.json no es válido. Ejecuta «npm run validar» para ver el motivo.');
  process.exit(1);
}

const filasUnidades = unidades.map(u => `  (${texto(u.id)}, ${u.numero}, ${texto(u.titulo)})`);
const filasLecciones = [];
for (const u of unidades) {
  for (const [i, id] of u.lecciones.entries()) {
    let titulo = id;
    let ejercicios = 0;
    try {
      const r = revisarLeccion(id, await leer(`lessons/${id}.json`));
      if (r.leccion) {
        titulo = r.leccion.titulo;
        ejercicios = r.leccion.idsEjercicios.length;
      }
    } catch {
      console.warn(`⚠ lessons/${id}.json no se puede leer: se registra con su id como título.`);
    }
    filasLecciones.push(`  (${texto(id)}, ${texto(u.id)}, ${i + 1}, ${texto(titulo)}, ${ejercicios})`);
  }
}

const sql = `-- =============================================================================
-- Olá! Learn Portuguese — course catalogue (units and lessons)
-- GENERATED by \`npm run catalogo-sql\` from lessons/curso.json. Do not edit by hand.
-- Run it in Supabase → SQL Editor AFTER supabase/esquema.sql, and again whenever
-- lessons are added. It only inserts/updates: it never deletes progress.
-- =============================================================================

begin;

insert into public.portuguese_units (id, position, title) values
${filasUnidades.join(',\n')}
on conflict (id) do update
  set position = excluded.position,
      title = excluded.title;

insert into public.portuguese_lessons (id, unit_id, position, title, exercise_count) values
${filasLecciones.join(',\n')}
on conflict (id) do update
  set unit_id = excluded.unit_id,
      position = excluded.position,
      title = excluded.title,
      exercise_count = excluded.exercise_count;

commit;
`;

await writeFile(path.join(raiz, 'supabase/catalogo.sql'), sql);
console.log(`supabase/catalogo.sql: ${unidades.length} units, ${filasLecciones.length} lessons.`);
